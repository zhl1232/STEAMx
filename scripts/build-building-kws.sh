#!/usr/bin/env bash
# Rebuild the checked-in, same-origin KWS bundle. No deploy or external publication.
set -euo pipefail
: "${KWS_SOURCE:?Set KWS_SOURCE to a sherpa-onnx v1.12.15 checkout}"
: "${KWS_MODEL:?Set KWS_MODEL to the extracted wenetspeech-3.3M-2024-01-01 model}"
: "${EMSCRIPTEN:?Set EMSCRIPTEN to the Emscripten 3.1.53 directory}"
repo_root=$(cd "$(dirname "$0")/.." && pwd)
expected=b68e69dd1a41dff6bcb8d31bf91dd3ba6b0dc568
[ "$(git -C "$KWS_SOURCE" rev-parse HEAD)" = "$expected" ] || { echo 'Unexpected sherpa-onnx revision'; exit 1; }
"$EMSCRIPTEN/emcc" --version | head -1 | grep -F '3.1.53' >/dev/null
export KWS_SOURCE KWS_MODEL
export KWS_MANIFEST="$repo_root/public/courses/kws/v1/model-source.json"
python3 - <<'PY'
import os,subprocess,shutil,hashlib,json
from pathlib import Path
source=Path(os.environ['KWS_SOURCE']); model=Path(os.environ['KWS_MODEL'])
for name, expected in json.loads(Path(os.environ['KWS_MANIFEST']).read_text()).items():
 if name=='archive': continue
 data=(model/name).read_bytes()
 if len(data)!=expected['bytes'] or hashlib.sha256(data).hexdigest()!=expected['sha256']: raise RuntimeError('Model integrity: '+name)
cmake=subprocess.check_output(['git','-C',str(source),'show','HEAD:wasm/kws/CMakeLists.txt'],text=True)
cmake=cmake.replace('  SherpaOnnxDestroyKeywordResult','  SherpaOnnxDestroyOnlineStream\n  SherpaOnnxCreateKeywordStreamWithKeywords\n  SherpaOnnxDestroyKeywordResult')
cmake=cmake.replace('INITIAL_MEMORY=512MB -s ALLOW_MEMORY_GROWTH=1','INITIAL_MEMORY=64MB -s MAXIMUM_MEMORY=256MB -s ALLOW_MEMORY_GROWTH=1 -s MODULARIZE=1 -s EXPORT_ES6=1 -s ENVIRONMENT=web,worker')

cmake=cmake.replace("'UTF8ToString']", "'UTF8ToString','HEAPU8','HEAPF32']")
(source/'wasm/kws/CMakeLists.txt').write_text(cmake)
assets=source/'wasm/kws/assets'
# Only the three selected INT8 weights and tokens are embedded; no English lexicon or recordings.
for f in assets.iterdir():
 if f.is_file(): f.unlink()
for name in ['encoder','decoder','joiner']:
 stem=name+'-epoch-12-avg-2-chunk-16-left-64'
 shutil.copyfile(model/(stem+'.int8.onnx'),assets/(stem+'.onnx'))
shutil.copyfile(model/'tokens.txt',assets/'tokens.txt')
PY
export SHERPA_ONNX_IS_USING_BUILD_WASM_SH=ON
cmake -S "$KWS_SOURCE" -B "$KWS_SOURCE/build-wasm-simd-kws" \
  -DCMAKE_INSTALL_PREFIX="$KWS_SOURCE/build-wasm-simd-kws/install" -DCMAKE_BUILD_TYPE=Release \
  -DCMAKE_TOOLCHAIN_FILE="$EMSCRIPTEN/cmake/Modules/Platform/Emscripten.cmake" \
  -DSHERPA_ONNX_ENABLE_PYTHON=OFF -DSHERPA_ONNX_ENABLE_TESTS=OFF -DSHERPA_ONNX_ENABLE_CHECK=OFF \
  -DBUILD_SHARED_LIBS=OFF -DSHERPA_ONNX_ENABLE_PORTAUDIO=OFF -DSHERPA_ONNX_ENABLE_JNI=OFF \
  -DSHERPA_ONNX_ENABLE_C_API=ON -DSHERPA_ONNX_ENABLE_TTS=OFF -DSHERPA_ONNX_ENABLE_WEBSOCKET=OFF \
  -DSHERPA_ONNX_ENABLE_GPU=OFF -DSHERPA_ONNX_ENABLE_WASM=ON -DSHERPA_ONNX_ENABLE_WASM_KWS=ON \
  -DSHERPA_ONNX_ENABLE_BINARY=OFF -DSHERPA_ONNX_LINK_LIBSTDCPP_STATICALLY=OFF
cmake --build "$KWS_SOURCE/build-wasm-simd-kws" --target sherpa-onnx-wasm-kws-main --parallel 2
export KWS_OUTPUT="$repo_root/public/courses/kws/v1"
python3 - <<'PY'
import os,shutil,hashlib,json
from pathlib import Path
source=Path(os.environ['KWS_SOURCE']); output=Path(os.environ['KWS_OUTPUT'])
manifest={}
for ext in ['js','wasm','data']:
 name='sherpa-onnx-wasm-kws-main.'+ext
 f=source/'build-wasm-simd-kws/bin'/name
 shutil.copyfile(f,output/name)
 data=f.read_bytes();manifest[name]={'bytes':len(data),'sha256':hashlib.sha256(data).hexdigest()}
binding=(source/'wasm/kws/sherpa-onnx-kws.js').read_text()
binding=binding[:binding.index("if (typeof process == 'object'")]
binding=binding.replace('config.keywordsBufLen,', 'config.keywordsBufSize,')
binding=binding.replace('  createStream() {\n    let handle = this.Module._SherpaOnnxCreateKeywordStream(this.handle);', '''  createStream(keywords) {
    let handle;
    if (keywords) {
      const length = this.Module.lengthBytesUTF8(keywords) + 1;
      const buffer = this.Module._malloc(length);
      try {
        this.Module.stringToUTF8(keywords, buffer, length);
        handle = this.Module._SherpaOnnxCreateKeywordStreamWithKeywords(this.handle, buffer);
      } finally { this.Module._free(buffer); }
    } else {
      handle = this.Module._SherpaOnnxCreateKeywordStream(this.handle);
    }''')
binding=binding[:binding.index('function createKws(')]+"function createKws(Module, config) {\n  if (!config) throw new Error('An explicit KWS configuration is required');\n  return new Kws(config, Module);\n}\n"
(output/'sherpa-onnx-kws.js').write_text('// Adapted from sherpa-onnx v1.12.15, Apache-2.0. See NOTICE.md.\n'+binding+'\nexport { createKws };\n')
(output/'assets.js').write_text('// Generated by scripts/build-building-kws.sh; version the directory when changing assets.\nexport const assets = '+json.dumps(manifest,indent=2)+'\n')
print(json.dumps(manifest,indent=2))
PY
