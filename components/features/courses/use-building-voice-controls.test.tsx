import { act, renderHook } from '@testing-library/react'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { useBuildingVoiceControls, type BuildingVoiceControlsOptions } from './use-building-voice-controls'
import type { BuildingVoiceCapture, BuildingVoiceCaptureOptions } from './building-voice-capture'
import type { BuildingVoiceCommand } from '@/lib/courses/building-voice-commands'
import { claimTutorAudioSession } from '@/components/features/tutor/tutor-audio-session'
const mocks = vi.hoisted(() => ({ createCapture: vi.fn(), fetch: vi.fn() }))
vi.mock('./building-voice-capture', () => ({ createBuildingVoiceCapture: mocks.createCapture }))
const options = (): BuildingVoiceControlsOptions => ({ courseId: 5, lessonId: 30, userId: 'user-a', navigationKey: 'visit-0', stepIndex: 1, stepCount: 5, onNavigate: vi.fn() })
const callbacks = (index = 0): BuildingVoiceCaptureOptions => mocks.createCapture.mock.calls[index][0]
const emit = (command: BuildingVoiceCommand, index = 0) => act(() => callbacks(index).onCommand(command))
const response = () => new Response(JSON.stringify({ userId: 'user-a', validForMs: 300000 }))
let capture: BuildingVoiceCapture
beforeEach(() => {
  vi.useFakeTimers()
  vi.resetAllMocks()
  capture = { setListening: vi.fn(), reset: vi.fn(), checkHealth: vi.fn(), playCue: vi.fn(), close: vi.fn().mockResolvedValue(undefined) }
  mocks.createCapture.mockImplementation(async (opts: BuildingVoiceCaptureOptions) => { await opts.authorized; return capture })
  mocks.fetch.mockImplementation(async () => response())
  vi.stubGlobal('fetch', mocks.fetch)
})
afterEach(() => { vi.useRealTimers(); vi.unstubAllGlobals() })
describe('local course voice lifecycle', () => {
  it('requires an explicit authenticated click and only fetches eligibility (no audio body)', async () => {
    const opts = options()
    const { result } = renderHook(() => useBuildingVoiceControls(opts))
    expect(mocks.fetch).not.toHaveBeenCalled()
    expect(mocks.createCapture).not.toHaveBeenCalled()
    await act(async () => { await result.current.start(); await result.current.start() })
    expect(mocks.createCapture).toHaveBeenCalledOnce()
    const [url, init] = mocks.fetch.mock.calls[0]
    expect(url).toBe('/api/tutor/speech/course-control?courseId=5&lessonId=30')
    expect(init.body).toBeUndefined()
    emit('next')
    expect(opts.onNavigate).toHaveBeenCalledExactlyOnceWith(2)
    emit('next')
    act(() => vi.advanceTimersByTime(1199))
    emit('next')
    expect(opts.onNavigate).toHaveBeenCalledOnce()
    act(() => vi.advanceTimersByTime(1))
    emit('previous')
    expect(opts.onNavigate).toHaveBeenLastCalledWith(0)
    expect(mocks.fetch).toHaveBeenCalledOnce()
  })
  it('does not start for anonymous visitors', async () => {
    const { result } = renderHook(() => useBuildingVoiceControls({ ...options(), userId: null }))
    await act(async () => result.current.start())
    expect(mocks.createCapture).not.toHaveBeenCalled()
    expect(mocks.fetch).not.toHaveBeenCalled()
  })
  it.each([['next', 4, '最后'], ['previous', 0, '第一']] as const)('handles %s page boundary', async (command, stepIndex, text) => {
    const opts = { ...options(), stepIndex }
    const { result } = renderHook(() => useBuildingVoiceControls(opts))
    await act(async () => result.current.start())
    emit(command)
    expect(opts.onNavigate).not.toHaveBeenCalled()
    expect(result.current.feedback).toContain(text)
  })
  it.each([['pause', 'paused'], ['exit', 'idle']] as const)('handles complete %s, resumes only on a click', async (command, status) => {
    const { result } = renderHook(() => useBuildingVoiceControls(options()))
    await act(async () => result.current.start())
    emit(command)
    expect(capture.close).toHaveBeenCalledOnce()
    expect(callbacks().signal.aborted).toBe(true)
    expect(result.current.status).toBe(status)
    act(() => vi.advanceTimersByTime(300000))
    expect(mocks.createCapture).toHaveBeenCalledOnce()
    await act(async () => result.current.resume())
    expect(mocks.createCapture).toHaveBeenCalledTimes(2)
  })
  it('keeps working on hidden pages but pauses for pagehide/freeze', async () => {
    const opts = options()
    const { result } = renderHook(() => useBuildingVoiceControls(opts))
    await act(async () => result.current.start())
    Object.defineProperty(document, 'visibilityState', { configurable: true, value: 'hidden' })
    act(() => document.dispatchEvent(new Event('visibilitychange')))
    expect(capture.checkHealth).toHaveBeenCalled()
    expect(result.current.status).toBe('listening')
    emit('next')
    expect(opts.onNavigate).toHaveBeenCalledOnce()
    act(() => window.dispatchEvent(new Event('pagehide')))
    expect(result.current.status).toBe('paused')
    act(() => window.dispatchEvent(new Event('pageshow')))
    expect(mocks.createCapture).toHaveBeenCalledOnce()
    await act(async () => result.current.resume())
    act(() => document.dispatchEvent(new Event('freeze')))
    expect(result.current.status).toBe('paused')
  })
  it('invalidates capture on A-B-A navigation, then uses the current page', async () => {
    const opts = options()
    const { result, rerender } = renderHook((props) => useBuildingVoiceControls(props), { initialProps: opts })
    await act(async () => result.current.start())
    rerender({ ...opts, navigationKey: 'B', stepIndex: 2 })
    rerender({ ...opts, navigationKey: 'A-again', stepIndex: 1 })
    expect(capture.reset).toHaveBeenCalledTimes(2)
    emit('next')
    expect(opts.onNavigate).toHaveBeenLastCalledWith(2)
  })
  it.each(['lessonId', 'courseId', 'userId'] as const)('releases and rejects late results on %s changes', async (key) => {
    const opts = options()
    const { result, rerender } = renderHook((props) => useBuildingVoiceControls(props), { initialProps: opts })
    await act(async () => result.current.start())
    rerender({ ...opts, [key]: key === 'userId' ? 'user-b' : 100 })
    emit('next')
    expect(opts.onNavigate).not.toHaveBeenCalled()
    expect(capture.close).toHaveBeenCalledOnce()
    expect(result.current.status).toBe('idle')
  })
  it('respects actual audio-session preemption including during cue playback', async () => {
    const opts = options()
    const { result } = renderHook(() => useBuildingVoiceControls(opts))
    await act(async () => result.current.start())
    let release = () => {}
    vi.mocked(capture.playCue).mockImplementation(() => { release = claimTutorAudioSession('tutor', () => {}) })
    emit('next')
    expect(opts.onNavigate).not.toHaveBeenCalled()
    expect(result.current.status).toBe('paused')
    release()
    act(() => vi.advanceTimersByTime(2000))
    expect(result.current.status).toBe('paused')
  })
  it('closes a late microphone result after pause', async () => {
    let resolve!: (value: BuildingVoiceCapture) => void
    mocks.createCapture.mockImplementation(() => new Promise((done) => { resolve = done }))
    const { result } = renderHook(() => useBuildingVoiceControls(options()))
    let pending!: Promise<void>
    act(() => { pending = result.current.start() })
    act(() => result.current.pause())
    await act(async () => { resolve(capture); await pending })
    expect(capture.close).toHaveBeenCalledOnce()
    expect(capture.setListening).not.toHaveBeenCalled()
  })
  it.each([401, 403, 503])('fails closed on eligibility HTTP %s without retries', async (status) => {
    mocks.fetch.mockResolvedValue(new Response('{}', { status }))
    const { result } = renderHook(() => useBuildingVoiceControls(options()))
    await act(async () => result.current.start())
    expect(result.current.status).toBe('error')
    act(() => vi.advanceTimersByTime(300000))
    expect(mocks.fetch).toHaveBeenCalledOnce()
  })
  it('renews eligibility without audio; stops on renewal failure', async () => {
    const { result } = renderHook(() => useBuildingVoiceControls(options()))
    await act(async () => result.current.start())
    await act(async () => vi.advanceTimersByTimeAsync(240000))
    expect(mocks.fetch).toHaveBeenCalledTimes(2)
    expect(mocks.createCapture).toHaveBeenCalledOnce()
    mocks.fetch.mockRejectedValue(new Error('offline'))
    await act(async () => vi.advanceTimersByTimeAsync(240000))
    expect(result.current.status).toBe('error')
    expect(capture.close).toHaveBeenCalledOnce()
  })
  it('rejects results after lease expiry even if a background timer has not run', async () => {
    const opts = options()
    const { result } = renderHook(() => useBuildingVoiceControls(opts))
    await act(async () => result.current.start())
    vi.setSystemTime(Date.now() + 300001)
    emit('next')
    expect(opts.onNavigate).not.toHaveBeenCalled()
    expect(result.current.status).toBe('paused')
  })
  it('cleans up capture, eligibility fetch, feedback and renewal on unmount', async () => {
    const opts = options()
    const { result, unmount } = renderHook(() => useBuildingVoiceControls(opts))
    await act(async () => result.current.start())
    unmount()
    emit('next')
    expect(capture.close).toHaveBeenCalledOnce()
    expect(callbacks().signal.aborted).toBe(true)
    expect(opts.onNavigate).not.toHaveBeenCalled()
    expect(vi.getTimerCount()).toBe(0)
  })
})
