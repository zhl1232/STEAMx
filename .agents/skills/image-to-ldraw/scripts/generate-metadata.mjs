#!/usr/bin/env node
/**
 * generate-metadata.mjs
 *
 * Reads duplo-parts-index.json and generates part-metadata.json entries
 * for Duplo parts that don't already have manual entries.
 *
 * Strategy:
 *   - For standard bricks/plates with clear NxM footprint: compute from formula
 *   - For other parts: compute what we can, mark needsManualReview
 *   - Never overwrite existing hand-tuned entries
 *
 * Usage:
 *   node scripts/generate-metadata.mjs [--dry-run] [--filter brick,plate,slope]
 */
import { readFile, writeFile } from 'node:fs/promises'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url))
const SKILL_ROOT = resolve(SCRIPT_DIR, '..')
const INDEX_PATH = resolve(SKILL_ROOT, 'references/duplo-parts-index.json')
const METADATA_PATH = resolve(SKILL_ROOT, 'references/part-metadata.json')

const STUD_PITCH = 40  // 1 Duplo stud = 40 LDU
const BRICK_HEIGHT = 48
const PLATE_HEIGHT = 24

function parseArgs(argv) {
  const args = { dryRun: false, filter: null, maxParts: null }
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--dry-run') args.dryRun = true
    else if (argv[i] === '--filter' && argv[i + 1]) args.filter = argv[++i].split(',')
    else if (argv[i] === '--max' && argv[i + 1]) args.maxParts = parseInt(argv[++i])
  }
  return args
}

/**
 * Determine if a part from the index is a "real" part we should generate metadata for.
 * Excludes sub-parts (s\ prefix) and printed variants (pNN suffix).
 */
function isRealPart(part) {
  const id = part.partId
  // Skip sub-parts
  if (id.startsWith('s\\') || id.startsWith('s/')) return false
  // Skip printed variants (e.g. 10715p01.dat)
  if (/p\d+\.dat$/.test(id)) return false
  // Skip shortcut/alias parts (start with ~ in description)
  if (part.description.startsWith('~')) return false
  // Skip "=" prefix (alias)
  if (part.description.startsWith('=')) return false
  return true
}

/**
 * Compute metadata for a standard rectangular part (brick or plate).
 */
function computeRectangularMetadata(part, category) {
  const fp = part.studFootprint
  if (!fp || !fp.x || !fp.z) return null

  const heightLdu = category === 'plate' ? PLATE_HEIGHT : BRICK_HEIGHT

  // Check for explicit height in description (e.g. "2 x 2 x 2")
  let actualHeight = heightLdu
  if (fp.height && fp.height > 1) {
    // "2 x 2 x 2" means 2 brick-heights tall
    actualHeight = fp.height * BRICK_HEIGHT
  }

  const halfX = (fp.x * STUD_PITCH) / 2
  const halfZ = (fp.z * STUD_PITCH) / 2

  return {
    name: part.description,
    category,
    ldrawStatus: part.source === 'official' ? 'Official' : 'Unofficial',
    studFootprint: { x: fp.x, z: fp.z },
    heightLdu: actualHeight,
    bbox: {
      xMin: -halfX, xMax: halfX,
      yMin: 0, yMax: actualHeight,
      zMin: -halfZ, zMax: halfZ,
    },
    origin: { type: 'top-center', originToTop: 0, originToBottom: actualHeight },
    connectionSurfaces: {
      top: { yLdu: 0, xMin: -halfX, xMax: halfX, zMin: -halfZ, zMax: halfZ },
      bottom: { yLdu: actualHeight, xMin: -halfX, xMax: halfX, zMin: -halfZ, zMax: halfZ },
    },
    collisionVolumes: [
      { xMin: -halfX, xMax: halfX, yMin: 0, yMax: actualHeight, zMin: -halfZ, zMax: halfZ },
    ],
    allowedOrientations: ['north', 'east', 'south', 'west'],
    supportPolicy: 'structural',
    autoGenerated: true,
  }
}

/**
 * Compute metadata for a slope part (approximate as full rectangular).
 */
function computeSlopeMetadata(part) {
  const fp = part.studFootprint
  if (!fp || !fp.x || !fp.z) return null

  // Slopes typically have a height multiplier in the description
  let heightMultiplier = 1
  if (fp.height) heightMultiplier = fp.height

  const heightLdu = heightMultiplier * BRICK_HEIGHT
  const halfX = (fp.x * STUD_PITCH) / 2
  const halfZ = (fp.z * STUD_PITCH) / 2

  return {
    name: part.description,
    category: 'slope',
    ldrawStatus: part.source === 'official' ? 'Official' : 'Unofficial',
    studFootprint: { x: fp.x, z: fp.z },
    heightLdu,
    bbox: {
      xMin: -halfX, xMax: halfX,
      yMin: 0, yMax: heightLdu,
      zMin: -halfZ, zMax: halfZ,
    },
    origin: { type: 'top-center', originToTop: 0, originToBottom: heightLdu },
    connectionSurfaces: {
      top: { yLdu: 0, xMin: -halfX, xMax: halfX, zMin: -halfZ, zMax: halfZ },
      bottom: { yLdu: heightLdu, xMin: -halfX, xMax: halfX, zMin: -halfZ, zMax: halfZ },
    },
    collisionVolumes: [
      { xMin: -halfX, xMax: halfX, yMin: 0, yMax: heightLdu, zMin: -halfZ, zMax: halfZ },
    ],
    allowedOrientations: ['north', 'east', 'south', 'west'],
    supportPolicy: 'structural',
    autoGenerated: true,
    needsManualReview: true,
    notes: ['Auto-generated: collision volume is full rectangular approximation for a slope. Actual slope geometry is smaller.'],
  }
}

/**
 * Compute metadata for an arch part (approximate).
 */
function computeArchMetadata(part) {
  const fp = part.studFootprint
  if (!fp || !fp.x || !fp.z) return null

  let heightMultiplier = fp.height || 2
  const heightLdu = heightMultiplier * BRICK_HEIGHT
  const halfX = (fp.x * STUD_PITCH) / 2
  const halfZ = (fp.z * STUD_PITCH) / 2

  return {
    name: part.description,
    category: 'arch',
    ldrawStatus: part.source === 'official' ? 'Official' : 'Unofficial',
    studFootprint: { x: fp.x, z: fp.z },
    heightLdu,
    bbox: {
      xMin: -halfX, xMax: halfX,
      yMin: 0, yMax: heightLdu,
      zMin: -halfZ, zMax: halfZ,
    },
    origin: { type: 'top-center', originToTop: 0, originToBottom: heightLdu },
    connectionSurfaces: {
      top: { yLdu: 0, xMin: -halfX, xMax: halfX, zMin: -halfZ, zMax: halfZ },
      bottom: { yLdu: heightLdu, xMin: -halfX, xMax: halfX, zMin: -halfZ, zMax: halfZ },
    },
    collisionVolumes: [
      { xMin: -halfX, xMax: halfX, yMin: 0, yMax: heightLdu, zMin: -halfZ, zMax: halfZ },
    ],
    allowedOrientations: ['north', 'east', 'south', 'west'],
    supportPolicy: 'structural',
    autoGenerated: true,
    needsManualReview: true,
    notes: ['Auto-generated: collision volume is full rectangular approximation. Arch opening is not modeled.'],
  }
}

/**
 * Generate metadata for a single part.
 */
function generateMetadata(part) {
  const cat = part.category

  if (cat === 'brick') return computeRectangularMetadata(part, 'brick')
  if (cat === 'plate') return computeRectangularMetadata(part, 'plate')
  if (cat === 'slope') return computeSlopeMetadata(part)
  if (cat === 'arch') return computeArchMetadata(part)
  if (cat === 'vehicle-base') return computeRectangularMetadata(part, 'vehicle-base')
  if (cat === 'fence') return computeRectangularMetadata(part, 'fence')
  if (cat === 'container') return computeRectangularMetadata(part, 'container')
  if (cat === 'slide') return computeRectangularMetadata(part, 'slide')

  // For other categories (figure, wheel, plant, window-door, etc.),
  // try rectangular approximation if footprint is available
  if (part.studFootprint && part.studFootprint.x && part.studFootprint.z) {
    const meta = computeRectangularMetadata(part, cat)
    if (meta) {
      meta.needsManualReview = true
      meta.notes = [`Auto-generated: rectangular approximation for ${cat} part. Actual geometry may differ significantly.`]
      return meta
    }
  }

  return null
}

async function main() {
  const args = parseArgs(process.argv.slice(2))

  // Load existing metadata
  const existingMetadata = JSON.parse(await readFile(METADATA_PATH, 'utf8'))
  const existingPartIds = new Set(Object.keys(existingMetadata.parts || {}))

  // Load index
  const index = JSON.parse(await readFile(INDEX_PATH, 'utf8'))

  // Filter to real parts only
  let partsToProcess = index.parts.filter(isRealPart)

  // Apply category filter if specified
  if (args.filter) {
    partsToProcess = partsToProcess.filter(p => args.filter.includes(p.category))
  }

  // Apply max limit
  if (args.maxParts) {
    partsToProcess = partsToProcess.slice(0, args.maxParts)
  }

  console.log(`Processing ${partsToProcess.length} parts (${existingPartIds.size} already in metadata)`)

  const generated = []
  const skipped = []
  const failed = []
  const preserved = []

  for (const part of partsToProcess) {
    const partId = part.partId

    // Never overwrite existing entries
    if (existingPartIds.has(partId)) {
      preserved.push(partId)
      continue
    }

    const meta = generateMetadata(part)
    if (meta) {
      generated.push({ partId, meta })
    } else {
      failed.push({ partId, reason: 'no footprint or unsupported category', description: part.description })
    }
  }

  console.log(`\nResults:`)
  console.log(`  Generated: ${generated.length}`)
  console.log(`  Preserved (existing): ${preserved.length}`)
  console.log(`  Failed (no footprint): ${failed.length}`)

  // Merge into metadata
  const newMetadata = JSON.parse(JSON.stringify(existingMetadata))
  for (const { partId, meta } of generated) {
    newMetadata.parts[partId] = meta
  }

  // Sort parts by partId for readability
  const sortedParts = {}
  for (const key of Object.keys(newMetadata.parts).sort()) {
    sortedParts[key] = newMetadata.parts[key]
  }
  newMetadata.parts = sortedParts

  const totalParts = Object.keys(newMetadata.parts).length
  console.log(`\nTotal parts in metadata: ${existingPartIds.size} → ${totalParts}`)

  // Category breakdown of generated parts
  const byCat = {}
  for (const { meta } of generated) {
    byCat[meta.category] = (byCat[meta.category] || 0) + 1
  }
  console.log('\nGenerated by category:')
  for (const [cat, count] of Object.entries(byCat).sort((a, b) => b[1] - a[1])) {
    const reviewCount = generated.filter(g => g.meta.category === cat && g.meta.needsManualReview).length
    console.log(`  ${cat}: ${count}${reviewCount > 0 ? ` (${reviewCount} need review)` : ''}`)
  }

  // Show failed parts
  if (failed.length > 0) {
    console.log(`\nFailed parts (${failed.length}):`)
    for (const f of failed.slice(0, 20)) {
      console.log(`  ${f.partId.padEnd(18)} ${f.description}`)
    }
    if (failed.length > 20) console.log(`  ... and ${failed.length - 20} more`)
  }

  // Write output
  if (args.dryRun) {
    console.log('\n[DRY RUN] No files written.')
    // Show a sample of what would be generated
    console.log('\nSample generated entries:')
    for (const { partId, meta } of generated.slice(0, 3)) {
      console.log(`\n  ${partId}:`)
      console.log(`    name: ${meta.name}`)
      console.log(`    category: ${meta.category}`)
      console.log(`    footprint: ${meta.studFootprint.x}x${meta.studFootprint.z}`)
      console.log(`    height: ${meta.heightLdu} LDU`)
      console.log(`    bbox: [${meta.bbox.xMin},${meta.bbox.xMax}] x [${meta.bbox.yMin},${meta.bbox.yMax}] x [${meta.bbox.zMin},${meta.bbox.zMax}]`)
      if (meta.needsManualReview) console.log(`    ⚠️  needs manual review`)
    }
  } else {
    await writeFile(METADATA_PATH, JSON.stringify(newMetadata, null, 2) + '\n', 'utf8')
    console.log(`\nWritten to: ${METADATA_PATH}`)
  }
}

main().catch((err) => {
  console.error(err.stack || err.message)
  process.exit(1)
})
