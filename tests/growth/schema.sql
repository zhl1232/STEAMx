-- Minimal dependency fixture. Uses the actual legacy functions/trigger migration
-- below; does not stand in for a full production-schema migration rehearsal.
CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role;
CREATE SCHEMA auth;
CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$ SELECT nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
CREATE FUNCTION auth.role() RETURNS text LANGUAGE sql STABLE AS $$ SELECT coalesce(nullif(current_setting('request.jwt.claim.role',true),''),'authenticated') $$;
CREATE TABLE public.profiles(id uuid PRIMARY KEY, role text DEFAULT 'user', xp integer DEFAULT 0, level integer DEFAULT 1,coins integer DEFAULT 0,last_check_in date,login_streak integer,total_login_days integer,is_auto_interaction_account boolean DEFAULT false);
CREATE FUNCTION public.is_moderator_or_admin() RETURNS boolean LANGUAGE sql STABLE SECURITY DEFINER AS $$ SELECT EXISTS(SELECT 1 FROM public.profiles WHERE id=auth.uid() AND role IN ('admin','moderator')) $$;
CREATE TABLE public.completed_projects(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id uuid REFERENCES public.profiles,project_id bigint,course_lesson_id uuid,record_kind text DEFAULT 'final',status text DEFAULT 'pending',moderation_state text DEFAULT 'pending', completed_at timestamptz DEFAULT now(),reviewed_by uuid,reviewed_at timestamptz,rejection_reason text,moderation_source text,proof_images text[] DEFAULT '{}',proof_captions text[],proof_video_url text,notes text,likes_count integer DEFAULT 0);
CREATE TABLE public.xp_logs(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),user_id uuid,action_type text,resource_id text,xp_amount integer,created_at timestamptz DEFAULT now(), UNIQUE(user_id,action_type,resource_id));
CREATE TABLE public.coin_logs(id bigint GENERATED ALWAYS AS IDENTITY,user_id uuid,amount integer,action_type text,resource_id text,UNIQUE(user_id,action_type,resource_id));

CREATE TABLE public.projects(id bigint PRIMARY KEY, author_id uuid, title text, description text, status text DEFAULT 'approved', moderation_state text DEFAULT 'approved');
CREATE TABLE public.project_steps(id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, project_id bigint, title text, description text, sort_order integer DEFAULT 0);
CREATE TABLE public.comments(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, project_id bigint REFERENCES public.projects ON DELETE CASCADE,author_id uuid REFERENCES public.profiles,content text,parent_id bigint REFERENCES public.comments ON DELETE CASCADE,reply_to_user_id uuid,reply_to_username text,image_url text,moderation_state text DEFAULT 'approved',created_at timestamptz DEFAULT now());
ALTER TABLE public.completed_projects ADD COLUMN is_public boolean DEFAULT true;

-- Journey column shapes and uniqueness follow 20260819100000. Load its real
-- follow-up hardening migration in run.sh so service-role guards are exercised.
CREATE TABLE auth.users(id uuid PRIMARY KEY);
CREATE TABLE public.challenges(id bigint PRIMARY KEY);
CREATE TABLE public.challenge_submissions(id bigint PRIMARY KEY,user_id uuid);
CREATE TABLE IF NOT EXISTS public.project_journeys (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  source_type text NOT NULL CHECK (source_type IN ('project', 'challenge')),
  project_id bigint REFERENCES public.projects(id) ON DELETE CASCADE,
  challenge_id bigint REFERENCES public.challenges(id) ON DELETE CASCADE,
  title text,
  project_goal text,
  attempt_no integer NOT NULL DEFAULT 1 CHECK (attempt_no > 0),
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'completed', 'abandoned')),
  started_at timestamptz NOT NULL DEFAULT now(),
  last_activity_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT project_journeys_source_check CHECK (
    (source_type = 'project' AND project_id IS NOT NULL AND challenge_id IS NULL)
    OR (source_type = 'challenge' AND challenge_id IS NOT NULL AND project_id IS NULL)
  )
);

CREATE INDEX IF NOT EXISTS idx_project_journeys_user_activity
  ON public.project_journeys (user_id, status, last_activity_at DESC);
CREATE INDEX IF NOT EXISTS idx_project_journeys_project
  ON public.project_journeys (project_id, user_id, status)
  WHERE source_type = 'project';
CREATE INDEX IF NOT EXISTS idx_project_journeys_challenge
  ON public.project_journeys (challenge_id, user_id, status)
  WHERE source_type = 'challenge';
CREATE UNIQUE INDEX IF NOT EXISTS project_journeys_one_active_project
  ON public.project_journeys (user_id, project_id)
  WHERE source_type = 'project' AND project_id IS NOT NULL AND status = 'active';
CREATE UNIQUE INDEX IF NOT EXISTS project_journeys_one_active_challenge
  ON public.project_journeys (user_id, challenge_id)
  WHERE source_type = 'challenge' AND challenge_id IS NOT NULL AND status = 'active';

CREATE TABLE IF NOT EXISTS public.project_journey_records (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  journey_id bigint NOT NULL REFERENCES public.project_journeys(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  record_kind text NOT NULL DEFAULT 'progress' CHECK (record_kind IN ('progress', 'final')),
  anchor_type text NOT NULL DEFAULT 'extra' CHECK (anchor_type IN ('step', 'stage', 'extra', 'final')),
  anchor_index smallint CHECK (anchor_index IS NULL OR anchor_index >= 0),
  title text,
  notes text,
  images text[] NOT NULL DEFAULT '{}'::text[],
  image_captions text[],
  video_url text,
  data jsonb,
  visibility text NOT NULL DEFAULT 'private' CHECK (visibility IN ('private', 'public')),
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'pending', 'approved', 'rejected')),
  moderation_state text NOT NULL DEFAULT 'approved',
  moderation_source text,
  rejection_reason text,
  reviewed_by uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  reviewed_at timestamptz,
  published_at timestamptz,
  legacy_source text,
  legacy_source_id bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT project_journey_records_kind_anchor_check CHECK (
    (record_kind = 'final' AND anchor_type = 'final')
    OR (record_kind = 'progress' AND anchor_type <> 'final')
  )
);

CREATE INDEX IF NOT EXISTS idx_project_journey_records_journey_time
  ON public.project_journey_records (journey_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_project_journey_records_public
  ON public.project_journey_records (visibility, status, moderation_state, published_at DESC)
  WHERE visibility = 'public';
CREATE INDEX IF NOT EXISTS idx_project_journey_records_legacy
  ON public.project_journey_records (legacy_source, legacy_source_id)
  WHERE legacy_source IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS project_journey_records_one_final
  ON public.project_journey_records (journey_id)
  WHERE record_kind = 'final';
CREATE UNIQUE INDEX IF NOT EXISTS project_journey_records_one_anchored_progress
  ON public.project_journey_records (journey_id, anchor_type, anchor_index)
  WHERE record_kind = 'progress'
    AND anchor_type IN ('step', 'stage')
    AND anchor_index IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS project_journey_records_one_legacy_source
  ON public.project_journey_records (legacy_source, legacy_source_id)
  WHERE legacy_source IS NOT NULL AND legacy_source_id IS NOT NULL;

