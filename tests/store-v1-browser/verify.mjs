import { chromium, expect } from '@playwright/test'
import fs from 'node:fs/promises'
const dir='/tmp/store-v1-review'
await fs.mkdir(dir,{recursive:true})
const browser=await chromium.launch({headless:true})
const errors=[],blocked=[]
let assertions=0
const check=async fn=>{await fn();assertions++}
try {
 for(const width of [390,1440]) {
  const context=await browser.newContext({viewport:{width,height:width===390?844:1000}})
  await context.route('**/*',route=>new URL(route.request().url()).hostname==='127.0.0.1'?route.continue():(blocked.push(route.request().url()),route.abort()))
  const page=await context.newPage()
  page.on('pageerror',e=>errors.push(e.message))
  page.on('console',msg=>{if(msg.type()==='error')errors.push(msg.text())})
  const go=query=>page.goto('http://127.0.0.1:3101/'+query,{waitUntil:'domcontentloaded'})
  const snap=async name=>{await page.screenshot({path:`${dir}/${name}-${width}.png`,fullPage:true});await check(async()=>expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy())}
  await go('?mode=catalog')
  await expect(page.getByRole('heading',{name:'通用科学实验材料套装',exact:true})).toBeVisible()
  await expect(page.getByRole('heading',{name:'2026分年级实验材料包',exact:true})).toBeVisible()
  await check(async()=>expect(await page.evaluate(()=>window.fixture.products.flatMap(p=>p.variants).length)).toBe(18))
  await check(async()=>expect(await page.evaluate(()=>JSON.stringify(window.fixture.products))).not.toMatch(/costCents|supplierSkuId|specId|sourceDraft/))
  await snap('catalog')
  await go('?mode=detail')
  await expect(page.getByText(/新疆维吾尔自治区每单/)).toBeVisible()
  await expect(page.getByText(/耗材用完后需补充/).first()).toBeVisible()
  const kits=await page.evaluate(()=>window.fixture.products[0].variants.map(v=>v.kit))
  const preparation=page.getByRole('region',{name:'所选规格材料'})
  await check(()=>expect(preparation.getByRole('heading',{level:2})).toHaveText(kits[0].name))
  await check(()=>expect(preparation.getByRole('listitem')).toHaveText(kits[0].materials))
  await check(()=>expect(preparation.getByRole('link',{name:'查看对应探索项目'})).toHaveAttribute('href',`/kits/${kits[0].slug}`))
  await check(()=>expect(page.getByRole('img',{name:'通用科学实验材料套装',exact:true})).toHaveAttribute('src',kits[0].cover_url))
  await page.getByRole('button',{name:'查看商品图片 2'}).click()
  await check(()=>expect(page.getByRole('button',{name:'查看商品图片 2'})).toHaveAttribute('aria-pressed','true'))
  await page.getByRole('button',{name:'一至二年级进阶368个实验款',exact:true}).click()
  await check(()=>expect(page.getByRole('button',{name:'一至二年级进阶368个实验款',exact:true})).toHaveAttribute('aria-pressed','true'))
  await check(()=>expect(preparation.getByRole('heading',{level:2})).toHaveText(kits[1].name))
  await check(()=>expect(preparation.getByRole('listitem')).toHaveText(kits[1].materials))
  await check(()=>expect(preparation.getByRole('link',{name:'查看对应探索项目'})).toHaveAttribute('href',`/kits/${kits[1].slug}`))
  await check(()=>expect(page.getByRole('img',{name:'通用科学实验材料套装',exact:true})).toHaveAttribute('src',kits[1].cover_url))
  if(kits[1].catalog.length) await check(()=>expect(preparation.getByText(kits[1].catalog.join('、'),{exact:true})).toBeVisible())
  else await check(()=>expect(preparation.getByRole('heading',{name:'实验目录',exact:true})).toHaveCount(0))
  await check(()=>expect(preparation.getByRole('img')).toHaveCount(kits[1].gallery_urls.length))
  await page.getByRole('spinbutton',{name:'数量'}).fill('0')
  await check(()=>expect(page.getByRole('button',{name:'请选择有效数量'})).toBeDisabled())
  await page.getByRole('spinbutton',{name:'数量'}).fill('1')
  await snap('detail')
  await go('?mode=detail&variant=00000000-0000-4000-8000-000000000000')
  await check(()=>expect(page.getByRole('button',{name:'暂无可售规格'})).toBeDisabled())
  await go('?mode=detail')
  await page.getByRole('button',{name:'立即购买'}).click()
  await page.waitForURL(/checkout/)
  await check(async()=>expect(new URL(page.url()).searchParams.get('intent')).toMatch(/^[a-f0-9-]{36}$/))
  await expect(page.getByText('¥11.44',{exact:true}).first()).toBeVisible()
  await page.getByRole('combobox',{name:/省份/}).selectOption('新疆维吾尔自治区')
  await check(()=>expect(page.getByText('¥43.44',{exact:true})).toBeVisible())
  await snap('checkout-xinjiang')
  await go('?mode=checkout&quantity=2&intent=two')
  await page.getByRole('combobox',{name:/省份/}).selectOption('新疆维吾尔自治区')
  await check(()=>expect(page.getByText('¥54.88',{exact:true})).toBeVisible())
  await page.getByRole('combobox',{name:/省份/}).selectOption('西藏自治区')
  await check(()=>expect(page.getByText('¥54.88',{exact:true})).toBeVisible())
  await page.getByRole('combobox',{name:/省份/}).selectOption('北京市')
  await check(()=>expect(page.getByText('¥22.88',{exact:true}).first()).toBeVisible())
  await go('?mode=support&scenario=send-error')
  await expect(page.getByText('你好，请描述遇到的问题。')).toBeVisible()
  await page.getByLabel('描述问题',{exact:true}).fill('材料缺件，如何处理？')
  await page.getByRole('button',{name:'发送留言'}).click()
  await check(()=>expect(page.getByRole('alert')).toContainText('发送暂时失败'))
  await page.getByRole('button',{name:'重试发送'}).click()
  await check(()=>expect(page.getByRole('log')).toContainText('材料缺件，如何处理？'))
  await check(async()=>expect(await page.evaluate(()=>window.fixture.sendPosts[0])).toEqual(await page.evaluate(()=>window.fixture.sendPosts[1])))
  await page.getByLabel('添加客服图片').setInputFiles('public/store/science-kits/general-starter-245.jpg')
  await page.getByRole('button',{name:'发送留言'}).click()
  await check(()=>expect(page.getByRole('log').getByRole('img')).toBeVisible())
  await snap('support-image')
  await go('?mode=catalog&scenario=empty')
  await check(()=>expect(page.getByRole('heading',{name:'商品正在准备中'})).toBeVisible())
  await context.close()
 }
 console.info(JSON.stringify({assertions,errors,blocked,screenshots:dir},null,2))
 if(errors.length||blocked.length)process.exitCode=1
} finally {await browser.close()}
