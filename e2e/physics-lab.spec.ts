// Range inputs use step=any: dispatch the same input event as a timeline drag.
async function scrubTimeline(timeline: import('@playwright/test').Locator, time: number) {
  await timeline.evaluate((element, value) => {
    (element as HTMLInputElement).value = String(value)
    element.dispatchEvent(new Event('input', { bubbles: true }))
  }, time)
}

async function animationFrames(page: import('@playwright/test').Page, count = 12) {
  await page.evaluate(frames => new Promise<void>(resolve => {
    let seen = 0
    const next = () => ++seen >= frames ? resolve() : requestAnimationFrame(next)
    requestAnimationFrame(next)
  }), count)
}

