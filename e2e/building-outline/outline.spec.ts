import { test, expect, type Page } from '@playwright/test'
const stats = (page: Page) => page.locator('canvas').evaluate((canvas: HTMLCanvasElement & {ldrawStats?: () => {renderedFrames:number;camera:number[];target:number[];calls:number}}) => canvas.ldrawStats!())
async function settled(page: Page) {
  await expect(page.locator('canvas')).toBeVisible()
  await expect.poll(async () => (await stats(page)).calls).toBeGreaterThan(1)
  await page.waitForTimeout(1000)
  const before = await stats(page)
  await page.waitForTimeout(300)
  expect((await stats(page)).renderedFrames).toBe(before.renderedFrames)
  return before
}
test('real model navigation, idle rendering, reduced motion and disposal', async ({page}, info) => {
  const errors: string[]=[]
  page.on('pageerror',error=>errors.push(error.message))
  const response = await page.request.get('/api/courses/ldraw-step?model=3-hu-die.mpd&step=0')
  expect((await response.text()).slice(0,6)).toBe('0 FILE')
  await page.goto('/')
  const first = await settled(page)
  await page.screenshot({path:info.outputPath('01-initial.png')})
  await page.getByRole('button',{name:'下一步',exact:true}).first().click()
  await page.waitForTimeout(150)
  await page.screenshot({path:info.outputPath('02-new-step-motion.png')})
  const second = await settled(page)
  expect(second.camera).toEqual(first.camera)
  expect(second.target).toEqual(first.target)
  await page.screenshot({path:info.outputPath('03-new-step-settled.png')})
  const size = page.viewportSize()!
  await page.setViewportSize({width: size.width-20,height: size.height-20})
  const resized = await settled(page)
  expect(resized.renderedFrames).toBeGreaterThan(second.renderedFrames)
  await page.setViewportSize(size)
  await page.getByRole('button',{name:'下一步',exact:true}).first().click({clickCount:3})
  await page.getByRole('button',{name:'上一步',exact:true}).first().click()
  await settled(page)
  await page.getByRole('button',{name:'空步骤',exact:true}).click()
  await settled(page)
  await page.screenshot({path:info.outputPath('04-wrap-up.png')})
  await page.emulateMedia({reducedMotion:'reduce'})
  await page.getByRole('button',{name:'换模型',exact:true}).click()
  await settled(page)
  await page.getByRole('button',{name:'下一步',exact:true}).first().click()
  await settled(page)
  await page.screenshot({path:info.outputPath('05-reduced-motion-model-switch.png')})
  await page.getByRole('button',{name:'挂载切换',exact:true}).click()
  await expect(page.locator('canvas')).toHaveCount(0)
  await page.getByRole('button',{name:'挂载切换',exact:true}).click()
  await settled(page)
  expect(errors).toEqual([])
  await info.attach('render-stats', {body: JSON.stringify({first,second,errors}),contentType:'application/json'})
})
