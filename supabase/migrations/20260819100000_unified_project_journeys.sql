CREATE POLICY "project_journeys_owner_or_public"
  ON public.project_journeys FOR SELECT
  USING (
    auth.uid() = user_id
    OR EXISTS (
      SELECT 1
      FROM public.profiles
      WHERE id = auth.uid() AND role IN ('admin', 'moderator')
    )
    OR EXISTS (
      SELECT 1
      FROM public.project_journey_records r
      WHERE r.journey_id = project_journeys.id
        AND r.visibility = 'public'
        AND r.status = 'approved'
        AND r.moderation_state = 'approved'
    )
  );

DROP POLICY IF EXISTS "project_journeys_owner_insert" ON public.project_journeys;
CREATE POLICY "project_journeys_owner_insert"
  ON public.project_journeys FOR INSERT
  WITH CHECK (auth.uid() = user_id);

