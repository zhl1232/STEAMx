CREATE OR REPLACE FUNCTION public.user_owns_project_journey(
  p_journey_id bigint,
  p_user_id uuid
)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT p_user_id = auth.uid()
    AND EXISTS (
      SELECT 1
      FROM public.project_journeys
      WHERE id = p_journey_id AND user_id = p_user_id
    );
$$;

REVOKE ALL ON FUNCTION public.user_owns_project_journey(bigint, uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.user_owns_project_journey(bigint, uuid) TO authenticated;

