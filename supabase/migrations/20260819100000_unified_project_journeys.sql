-- 普通项目过程记录/作品回填到统一记录表。
INSERT INTO public.project_journey_records (
  journey_id, user_id, record_kind, anchor_type, title, notes, images,
  image_captions, video_url, visibility, status, moderation_state,
  moderation_source, rejection_reason, reviewed_by, reviewed_at,
  legacy_source, legacy_source_id, created_at, updated_at, published_at
)
SELECT
  legacy.journey_id,
  legacy.user_id,
  CASE
    WHEN COALESCE(legacy.record_kind, 'final') = 'final' AND legacy.final_rank = 1 THEN 'final'
    ELSE 'progress'
  END,
  CASE
    WHEN COALESCE(legacy.record_kind, 'final') = 'final' AND legacy.final_rank = 1 THEN 'final'
    ELSE 'extra'
  END,
  legacy.project_title,
  legacy.notes,
  COALESCE(legacy.proof_images, '{}'::text[]),
  legacy.proof_captions,
  legacy.proof_video_url,
  CASE WHEN COALESCE(legacy.is_public, true) THEN 'public' ELSE 'private' END,
  COALESCE(legacy.status, 'pending'),
  COALESCE(legacy.moderation_state, 'approved'),
  legacy.moderation_source,
  legacy.rejection_reason,
  legacy.reviewed_by,
  legacy.reviewed_at,
  'completed_projects',
  legacy.id,
  COALESCE(legacy.completed_at, now()),
  COALESCE(legacy.completed_at, now()),
  CASE
    WHEN COALESCE(legacy.is_public, true)
      AND COALESCE(legacy.status, 'pending') = 'approved'
      AND COALESCE(legacy.moderation_state, 'approved') = 'approved'
    THEN COALESCE(legacy.completed_at, now())
    ELSE NULL
  END
FROM (
  SELECT
    cp.*,
    e.journey_id,
    p.title AS project_title,
    CASE
      WHEN COALESCE(cp.record_kind, 'final') = 'final' THEN row_number() OVER (
        PARTITION BY e.journey_id
        ORDER BY
          CASE WHEN cp.status = 'approved' THEN 0 WHEN cp.status = 'pending' THEN 1 ELSE 2 END,
          cp.completed_at DESC NULLS LAST,
          cp.id DESC
      )
      ELSE NULL
    END AS final_rank
  FROM public.completed_projects cp
  JOIN public.project_explorations e ON e.id = cp.exploration_id
  JOIN public.projects p ON p.id = cp.project_id
  WHERE cp.project_id IS NOT NULL
    AND cp.course_lesson_id IS NULL
) AS legacy
WHERE legacy.journey_id IS NOT NULL
  AND legacy.journey_record_id IS NULL
  AND NOT EXISTS (
    SELECT 1 FROM public.project_journey_records r
    WHERE r.legacy_source = 'completed_projects' AND r.legacy_source_id = legacy.id
  );

UPDATE public.completed_projects cp
