  user_id, project_id, status, started_at, last_activity_at, completed_at, created_at, updated_at
)
SELECT
  cp.user_id,
  cp.project_id,
  CASE
    WHEN bool_or(
      COALESCE(cp.record_kind, 'final') = 'final'
      AND cp.status IN ('pending', 'approved')
    ) THEN 'completed'
    ELSE 'active'
  END,
  min(COALESCE(cp.completed_at, now())),
  max(COALESCE(cp.completed_at, now())),
  max(cp.completed_at) FILTER (
    WHERE COALESCE(cp.record_kind, 'final') = 'final'
      AND cp.status IN ('pending', 'approved')
  ),
  min(COALESCE(cp.completed_at, now())),
  max(COALESCE(cp.completed_at, now()))
FROM public.completed_projects cp
WHERE cp.exploration_id IS NULL
  AND cp.project_id IS NOT NULL
  AND cp.course_lesson_id IS NULL
  AND NOT EXISTS (
    SELECT 1
    FROM public.project_explorations e
    WHERE e.user_id = cp.user_id AND e.project_id = cp.project_id
  )
GROUP BY cp.user_id, cp.project_id;

