-- 统一普通项目与 PBL 的「我的进行中项目」与过程记录。
-- 项目/挑战仍是内容来源；project_journeys 是某个用户的一次尝试；
-- project_journey_records 是私密草稿、公开过程记录或最终作品。

BEGIN;

CREATE TABLE IF NOT EXISTS public.project_journeys (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  source_type text NOT NULL CHECK (source_type IN ('project', 'challenge')),
  project_id bigint REFERENCES public.projects(id) ON DELETE CASCADE,
  challenge_id bigint REFERENCES public.challenges(id) ON DELETE CASCADE,
  title text,
  project_goal text,
  attempt_no integer NOT NULL DEFAULT 1 CHECK (attempt_no > 0),
  status text NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'completed', 'abandoned')),
  started_at timestamptz NOT NULL DEFAULT now(),
  last_activity_at timestamptz NOT NULL DEFAULT now(),
  completed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT project_journeys_source_check CHECK (
    (source_type = 'project' AND project_id IS NOT NULL AND challenge_id IS NULL)
    OR (source_type = 'challenge' AND challenge_id IS NOT NULL AND project_id IS NULL)
  )
);

CREATE INDEX IF NOT EXISTS idx_project_journeys_user_activity
  ON public.project_journeys (user_id, status, last_activity_at DESC);
CREATE INDEX IF NOT EXISTS idx_project_journeys_project
  ON public.project_journeys (project_id, user_id, status)
  WHERE source_type = 'project';
CREATE INDEX IF NOT EXISTS idx_project_journeys_challenge
  ON public.project_journeys (challenge_id, user_id, status)
  WHERE source_type = 'challenge';
CREATE UNIQUE INDEX IF NOT EXISTS project_journeys_one_active_project
  ON public.project_journeys (user_id, project_id)
  WHERE source_type = 'project' AND project_id IS NOT NULL AND status = 'active';
CREATE UNIQUE INDEX IF NOT EXISTS project_journeys_one_active_challenge
  ON public.project_journeys (user_id, challenge_id)
  WHERE source_type = 'challenge' AND challenge_id IS NOT NULL AND status = 'active';

CREATE TABLE IF NOT EXISTS public.project_journey_records (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  journey_id bigint NOT NULL REFERENCES public.project_journeys(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  record_kind text NOT NULL DEFAULT 'progress' CHECK (record_kind IN ('progress', 'final')),
  anchor_type text NOT NULL DEFAULT 'extra' CHECK (anchor_type IN ('step', 'stage', 'extra', 'final')),
  anchor_index smallint CHECK (anchor_index IS NULL OR anchor_index >= 0),
  title text,
  notes text,
  images text[] NOT NULL DEFAULT '{}'::text[],
  image_captions text[],
  video_url text,
  data jsonb,
  visibility text NOT NULL DEFAULT 'private' CHECK (visibility IN ('private', 'public')),
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'pending', 'approved', 'rejected')),
  moderation_state text NOT NULL DEFAULT 'approved',
  moderation_source text,
  rejection_reason text,
  reviewed_by uuid REFERENCES public.profiles(id) ON DELETE SET NULL,
  reviewed_at timestamptz,
  published_at timestamptz,
  legacy_source text,
  legacy_source_id bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT project_journey_records_kind_anchor_check CHECK (
    (record_kind = 'final' AND anchor_type = 'final')
    OR (record_kind = 'progress' AND anchor_type <> 'final')
  )
);

CREATE INDEX IF NOT EXISTS idx_project_journey_records_journey_time
  ON public.project_journey_records (journey_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_project_journey_records_public
