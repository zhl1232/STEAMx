-- Platform announcements, welcome settings, durable delivery ledger.
CREATE TABLE IF NOT EXISTS public.platform_announcements (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL CHECK (char_length(title) BETWEEN 1 AND 160),
  summary text NOT NULL DEFAULT '' CHECK (char_length(summary) <= 500),
  body text NOT NULL CHECK (char_length(body) BETWEEN 1 AND 50000),
  level text NOT NULL DEFAULT 'normal' CHECK (level IN ('normal','important','urgent')),
  status text NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','published','withdrawn')),
  action_label text CHECK (action_label IS NULL OR char_length(action_label) <= 80),
  action_href text CHECK (action_href IS NULL OR action_href LIKE '/%'),
  published_at timestamptz,
  expires_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (expires_at IS NULL OR published_at IS NULL OR expires_at > published_at)
);
CREATE INDEX IF NOT EXISTS platform_announcements_public_idx
  ON public.platform_announcements (status, published_at DESC, id DESC);

CREATE TABLE IF NOT EXISTS public.platform_welcome_settings (
  id boolean PRIMARY KEY DEFAULT true CHECK (id),
  enabled boolean NOT NULL DEFAULT true,
  title text NOT NULL DEFAULT '欢迎来到创探空间',
  body text NOT NULL DEFAULT '从兴趣出发，在动手中成长。你可以探索积木搭建、Scratch 编程、科学实验、自然观察、项目式学习和游乐场挑战，遇到问题随时联系我们。',
  contact_href text NOT NULL DEFAULT '/about#contact' CHECK (contact_href LIKE '/%'),
  activated_after timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
INSERT INTO public.platform_welcome_settings (id) VALUES (true) ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS public.communication_ledger (
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  event_key text NOT NULL,
  kind text NOT NULL CHECK (kind IN ('welcome','announcement')),
  announcement_id bigint REFERENCES public.platform_announcements(id) ON DELETE CASCADE,
  delivered_at timestamptz,
  read_at timestamptz,
  banner_dismissed_at timestamptz,
  popup_claimed_at timestamptz,
  notification_id bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, event_key)
);
CREATE INDEX IF NOT EXISTS communication_ledger_announcement_idx
  ON public.communication_ledger (announcement_id, user_id);

CREATE TABLE IF NOT EXISTS public.communication_worker_state (
  name text PRIMARY KEY,
  cursor uuid,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','done','error')),
  last_error text,
  attempts integer NOT NULL DEFAULT 0,
  next_run_at timestamptz NOT NULL DEFAULT now(),
  target_count bigint NOT NULL DEFAULT 0,
  updated_at timestamptz NOT NULL DEFAULT now()
);


