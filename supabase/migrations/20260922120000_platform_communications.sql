CREATE FUNCTION public.publish_platform_announcement_service(p_announcement_id bigint)
RETURNS public.platform_announcements LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE a public.platform_announcements;
BEGIN
  SELECT * INTO a FROM public.platform_announcements WHERE id=p_announcement_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'announcement not found'; END IF;
  IF a.status='withdrawn' THEN RAISE EXCEPTION 'withdrawn announcement cannot be published'; END IF;
  IF a.status='published' THEN RETURN a; END IF;
  IF a.expires_at IS NOT NULL AND a.expires_at <= now() THEN RAISE EXCEPTION 'expiration must be in the future'; END IF;
  UPDATE public.platform_announcements SET status='published',published_at=now() WHERE id=a.id RETURNING * INTO a;
  INSERT INTO public.communication_worker_state(name,target_count)
    SELECT 'announcement:' || a.id,count(*) FROM public.profiles WHERE created_at <= a.published_at;
  RETURN a;
END $$;

CREATE FUNCTION public.retry_platform_announcement_service(p_announcement_id bigint)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE a public.platform_announcements;
BEGIN
  SELECT * INTO a FROM public.platform_announcements WHERE id=p_announcement_id FOR SHARE;
  IF NOT FOUND OR a.status <> 'published' THEN RETURN false; END IF;
  UPDATE public.communication_worker_state SET status='pending',attempts=0,last_error=NULL,next_run_at=now()
    WHERE name='announcement:' || a.id AND status <> 'done';
  RETURN true;
END $$;

CREATE FUNCTION public.create_welcome_service(p_user_id uuid)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE s public.platform_welcome_settings; n_id bigint;
BEGIN
  PERFORM pg_advisory_xact_lock(hashtextextended('communication:' || p_user_id::text,0));
  SELECT * INTO s FROM public.platform_welcome_settings WHERE id=true FOR SHARE;
  IF NOT FOUND OR NOT s.enabled THEN RETURN false; END IF;
  IF NOT EXISTS(SELECT 1 FROM public.profiles WHERE id=p_user_id AND created_at >= s.activated_after) THEN RETURN false; END IF;
  IF EXISTS(SELECT 1 FROM public.communication_ledger WHERE user_id=p_user_id AND event_key='welcome' AND delivered_at IS NOT NULL) THEN RETURN false; END IF;
  INSERT INTO public.notifications(user_id,type,title,content,system_kind,from_username)
    VALUES(p_user_id,'system',s.title,s.body,'welcome','平台助手') RETURNING id INTO n_id;
  INSERT INTO public.communication_ledger(user_id,event_key,kind,delivered_at,notification_id)
    VALUES(p_user_id,'welcome','welcome',now(),n_id);
  RETURN true;
END $$;

CREATE FUNCTION public.deliver_announcement_service(p_user_id uuid,p_announcement_id bigint,p_title text,p_content text)
RETURNS bigint LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE a public.platform_announcements; l public.communication_ledger; n_id bigint;
BEGIN
  SELECT * INTO a FROM public.platform_announcements WHERE id=p_announcement_id FOR SHARE;
  IF NOT FOUND OR a.status <> 'published' OR NOT EXISTS(SELECT 1 FROM public.profiles WHERE id=p_user_id AND created_at<=a.published_at) THEN RETURN NULL; END IF;
  INSERT INTO public.communication_ledger(user_id,event_key,kind,announcement_id)
    VALUES(p_user_id,'announcement:' || a.id,'announcement',a.id) ON CONFLICT DO NOTHING;
  SELECT * INTO l FROM public.communication_ledger WHERE user_id=p_user_id AND event_key='announcement:' || a.id FOR UPDATE;
  IF l.delivered_at IS NOT NULL THEN RETURN l.notification_id; END IF;
  INSERT INTO public.notifications(user_id,type,title,content,system_kind,announcement_id,from_username,is_read)
    VALUES(p_user_id,'system',a.title,left(COALESCE(NULLIF(a.summary,''),a.body),500),'announcement',a.id,'平台助手',l.read_at IS NOT NULL) RETURNING id INTO n_id;
  UPDATE public.communication_ledger SET delivered_at=now(),notification_id=n_id
    WHERE user_id=p_user_id AND event_key=l.event_key;
  RETURN n_id;
END $$;

CREATE FUNCTION public.claim_announcement_popup_service(p_user_id uuid,p_announcement_id bigint)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE a public.platform_announcements; changed integer;
BEGIN
  SELECT * INTO a FROM public.platform_announcements WHERE id=p_announcement_id FOR SHARE;
  IF NOT FOUND OR a.status <> 'published' OR a.level <> 'urgent' OR a.published_at IS NULL OR (a.expires_at IS NOT NULL AND a.expires_at<=now()) THEN RETURN false; END IF;
  IF NOT EXISTS(SELECT 1 FROM public.profiles WHERE id=p_user_id AND created_at<=a.published_at) THEN RETURN false; END IF;
  INSERT INTO public.communication_ledger(user_id,event_key,kind,announcement_id)
    VALUES(p_user_id,'announcement:' || a.id,'announcement',a.id) ON CONFLICT DO NOTHING;
  UPDATE public.communication_ledger SET popup_claimed_at=now()
    WHERE user_id=p_user_id AND event_key='announcement:' || a.id AND popup_claimed_at IS NULL;
  GET DIAGNOSTICS changed=ROW_COUNT;
  RETURN changed=1;
END $$;

CREATE FUNCTION public.mark_communication_read_service(p_user_id uuid,p_event_key text)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE a_id bigint; n_id bigint;
BEGIN
  IF p_event_key ~ '^announcement:[0-9]+$' THEN
    a_id := split_part(p_event_key,':',2)::bigint;
    PERFORM 1 FROM public.platform_announcements WHERE id=a_id AND status='published' FOR SHARE;
    IF NOT FOUND THEN RETURN false; END IF;
  END IF;
  LOOP
    SELECT notification_id INTO n_id FROM public.communication_ledger
      WHERE user_id=p_user_id AND event_key=p_event_key;
    IF n_id IS NOT NULL THEN
      -- Match normal mark-read/mark-all: notification first, ledger second.
      UPDATE public.notifications SET is_read=true WHERE user_id=p_user_id AND id=n_id;
      UPDATE public.communication_ledger SET read_at=COALESCE(read_at,now())
        WHERE user_id=p_user_id AND event_key=p_event_key;
      RETURN true;
    END IF;
    BEGIN
      IF a_id IS NOT NULL THEN
        INSERT INTO public.communication_ledger(user_id,event_key,kind,announcement_id)
          VALUES(p_user_id,p_event_key,'announcement',a_id) ON CONFLICT DO NOTHING;
      END IF;
      SELECT notification_id INTO n_id FROM public.communication_ledger
        WHERE user_id=p_user_id AND event_key=p_event_key FOR UPDATE;
      IF NOT FOUND THEN RETURN false; END IF;
      IF n_id IS NOT NULL THEN
        -- Delivery won the race. Roll back this subtransaction to release its
        -- ledger lock before retrying in notification-first order.
        RAISE EXCEPTION 'delivery completed during read' USING ERRCODE='40001';
      END IF;
      UPDATE public.communication_ledger SET read_at=COALESCE(read_at,now())
        WHERE user_id=p_user_id AND event_key=p_event_key;
      RETURN true;
    EXCEPTION WHEN serialization_failure THEN
      NULL;
    END;
  END LOOP;
END $$;

-- The existing single/all-read APIs stay atomic with the ledger via a trigger.
CREATE FUNCTION public.sync_communication_notification_read()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
BEGIN
  IF NEW.is_read AND NEW.system_kind IS NOT NULL THEN
    UPDATE public.communication_ledger SET read_at=COALESCE(read_at,now()) WHERE user_id=NEW.user_id AND notification_id=NEW.id;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER communication_notification_read AFTER UPDATE OF is_read ON public.notifications
  FOR EACH ROW EXECUTE FUNCTION public.sync_communication_notification_read();

CREATE FUNCTION public.mark_all_communications_read_service(p_user_id uuid)
RETURNS integer LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE changed integer;
BEGIN
  UPDATE public.notifications SET is_read=true WHERE user_id=p_user_id AND system_kind IS NOT NULL AND NOT is_read;
  GET DIAGNOSTICS changed=ROW_COUNT;
  RETURN changed;
END $$;

CREATE FUNCTION public.run_announcement_batch_service(p_announcement_id bigint,p_limit integer DEFAULT 50)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = '' AS $$
DECLARE a public.platform_announcements; st public.communication_worker_state; p record; delivered integer:=0; scanned integer:=0; last_id uuid;
BEGIN
  SELECT * INTO a FROM public.platform_announcements WHERE id=p_announcement_id FOR SHARE;
  IF NOT FOUND OR a.status <> 'published' THEN RETURN jsonb_build_object('delivered',0,'done',true,'stopped',true); END IF;
  INSERT INTO public.communication_worker_state(name,target_count)
    SELECT 'announcement:' || a.id,count(*) FROM public.profiles WHERE created_at<=a.published_at ON CONFLICT DO NOTHING;
  SELECT * INTO st FROM public.communication_worker_state WHERE name='announcement:' || a.id FOR UPDATE;
  IF st.status='done' OR st.next_run_at>now() OR st.attempts>=5 THEN RETURN jsonb_build_object('delivered',0,'done',st.status='done'); END IF;
  -- Roll back an entire failed batch, then persist failure outside that subtransaction.
  BEGIN
    FOR p IN SELECT id FROM public.profiles WHERE created_at<=a.published_at AND (st.cursor IS NULL OR id>st.cursor)
      ORDER BY id LIMIT GREATEST(1,LEAST(COALESCE(p_limit,50),200)) LOOP
      last_id:=p.id;
      scanned:=scanned+1;
      IF NOT EXISTS(SELECT 1 FROM public.communication_ledger WHERE user_id=p.id AND event_key='announcement:' || a.id AND delivered_at IS NOT NULL) THEN
        PERFORM public.deliver_announcement_service(p.id,a.id,a.title,a.summary);
        delivered:=delivered+1;
      END IF;
    END LOOP;
    UPDATE public.communication_worker_state SET cursor=COALESCE(last_id,cursor),status=CASE WHEN scanned<GREATEST(1,LEAST(COALESCE(p_limit,50),200)) THEN 'done' ELSE 'pending' END,
      attempts=0,last_error=NULL,next_run_at=now(),updated_at=now() WHERE name=st.name;
    RETURN jsonb_build_object('delivered',delivered,'done',scanned<GREATEST(1,LEAST(COALESCE(p_limit,50),200)));
  EXCEPTION WHEN OTHERS THEN
    UPDATE public.communication_worker_state SET status='error',attempts=attempts+1,last_error=SQLERRM,
      next_run_at=now()+make_interval(secs=>LEAST(3600,30*(2^st.attempts)::integer)),updated_at=now() WHERE name=st.name;
    RETURN jsonb_build_object('delivered',0,'error',SQLERRM,'done',false);
  END;
END $$;

-- Authenticated notification updates may mark read, never forge platform content.
CREATE FUNCTION public.guard_communication_notification()
RETURNS trigger LANGUAGE plpgsql SET search_path = '' AS $$
BEGIN
  IF auth.role() IN ('anon','authenticated') THEN
    IF TG_OP='INSERT' AND NEW.system_kind IS NOT NULL THEN RAISE EXCEPTION 'platform notifications are server managed'; END IF;
    IF TG_OP='UPDATE' AND (NEW.system_kind IS NOT NULL OR OLD.system_kind IS NOT NULL)
      AND (to_jsonb(NEW)-'is_read') IS DISTINCT FROM (to_jsonb(OLD)-'is_read') THEN RAISE EXCEPTION 'platform notifications are server managed'; END IF;
  END IF;
  RETURN NEW;
END $$;
CREATE TRIGGER communication_notification_guard BEFORE INSERT OR UPDATE ON public.notifications
  FOR EACH ROW EXECUTE FUNCTION public.guard_communication_notification();

DO $$
DECLARE f regprocedure;
BEGIN
  FOR f IN SELECT p.oid::regprocedure FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace
    WHERE n.nspname='public' AND p.proname IN ('publish_platform_announcement_service','retry_platform_announcement_service','create_welcome_service','deliver_announcement_service','claim_announcement_popup_service','mark_communication_read_service','mark_all_communications_read_service','run_announcement_batch_service','sync_communication_notification_read','guard_communication_notification') LOOP
    EXECUTE format('REVOKE ALL ON FUNCTION %s FROM PUBLIC, anon, authenticated',f);
    EXECUTE format('GRANT EXECUTE ON FUNCTION %s TO service_role',f);
  END LOOP;
END $$;
NOTIFY pgrst, 'reload schema';

CREATE FUNCTION public.platform_announcement_stats_service()
RETURNS TABLE(announcement_id bigint,target bigint,delivered bigint,read bigint,failed bigint,pending bigint)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = '' AS $$
  SELECT a.id,COALESCE(st.target_count,0),count(l.delivered_at),count(l.read_at) FILTER(WHERE l.delivered_at IS NOT NULL),
    CASE WHEN st.status='error' THEN GREATEST(COALESCE(st.target_count,0)-count(l.delivered_at),0) ELSE 0 END,
    CASE WHEN a.status='published' THEN GREATEST(COALESCE(st.target_count,0)-count(l.delivered_at),0) ELSE 0 END
  FROM public.platform_announcements a
  LEFT JOIN public.communication_worker_state st ON st.name='announcement:' || a.id
  LEFT JOIN public.communication_ledger l ON l.announcement_id=a.id
  GROUP BY a.id,st.target_count,st.status;
$$;
REVOKE ALL ON FUNCTION public.platform_announcement_stats_service() FROM PUBLIC,anon,authenticated;
GRANT EXECUTE ON FUNCTION public.platform_announcement_stats_service() TO service_role;
NOTIFY pgrst, 'reload schema';
